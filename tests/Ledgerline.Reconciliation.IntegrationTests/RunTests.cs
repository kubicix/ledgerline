    [Fact]
    public async Task Run_with_incomplete_inputs_can_be_rerun()
    {
        var date = new DateOnly(2026, 11, 10);
        // The payment records stay unstaged until the gate opens, so their partitions are behind their high watermark
        // and the first run's input wait (3 s here) times out. The staging loop is single-threaded, so the ledger lines
        // are produced and staged first: a held payment record would hold back every record behind it.
        var gate = new TaskCompletionSource(TaskCreationOptions.RunContinuationsAsynchronously);
        await using var scenario = await StartAsync(date, overrides: services =>
        {
            services.RemoveAll<IStagingConsumer>();
            services.AddSingleton<IStagingConsumer, LedgerStagingConsumer>();
            services.AddSingleton<IStagingConsumer>(new GatedStagingConsumer(new PaymentStagingConsumer(), gate.Task));
        }, settings: new() { ["Reconciliation:Run:InputWaitTimeout"] = "00:00:03" }, produceInputs: false);
        RunRow first;
        try
        {
            await scenario.Host.WaitForCommitAsync(await scenario.ProduceLedgerAsync());
            await scenario.ProducePaymentsAsync();

            (await scenario.RunAsync()).ShouldBe(RunOutcome.Completed);
            first = await RunRowAsync(scenario.Host, date);
            (first.Status, first.InputsIncomplete, first.Matched).ShouldBe(("Completed", true, 0));
            // No payment staged yet: every bank row has an unknown reference.
            (await ItemsAsync(scenario.Host)).Select(x => x.Code).ShouldBe(["UnknownBankRecord", "UnknownBankRecord", "UnknownBankRecord"]);

            gate.TrySetResult();
            await scenario.Host.WaitForCommitAsync(scenario.Delivered);
            (await scenario.RunAsync()).ShouldBe(RunOutcome.Completed);
        }
        finally
        {
            gate.TrySetResult();
        }

        var second = await RunRowAsync(scenario.Host, date);
        // One row per date (C1), the same run id throughout.
        (await RowsAsync(scenario.Host, "SELECT id::text FROM reconciliation_runs")).ShouldBe([second.Id.ToString()]);
        second.Id.ShouldBe(first.Id);
        (second.Status, second.InputsIncomplete, second.Matched, second.Mismatched).ShouldBe(("Completed", false, 3, 0));
        (await ItemsAsync(scenario.Host)).ShouldBeEmpty();
        // Both completions published, each in its own transaction; the second adds the reconciled payments.
        var outbox = await OutboxAsync(scenario.Host);
        outbox.ShouldAllBe(x => x.CorrelationId == second.Id);
        outbox.Where(x => x.Type == CompletedType).Select(x => x.Payload<ReconciliationCompleted>().InputsIncomplete)
            .ShouldBe([true, false], ignoreOrder: true);
        outbox.Count(x => x.Type == MismatchType).ShouldBe(3);
        outbox.Single(x => x.Type == ReconciledType).Payload<PaymentsReconciled>().PaymentIds
            .ShouldBe(scenario.TopUps.Select(x => x.PaymentId).Order().ToList());
    }

