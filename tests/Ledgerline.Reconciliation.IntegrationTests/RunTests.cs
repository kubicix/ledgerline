    private static byte[] Wrap<T>(T payload) where T : notnull
    {
        var type = typeof(T).GetCustomAttribute<MessageTypeAttribute>()!.Name;
        return EnvelopeSerializer.Serialize(new MessageEnvelope(Guid.NewGuid(), type, DateTimeOffset.UtcNow, Guid.NewGuid(), null, null,
            EnvelopeSerializer.ToPayload(payload)));
    }

