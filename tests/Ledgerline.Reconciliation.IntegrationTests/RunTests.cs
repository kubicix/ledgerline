    private sealed class Scenario(StagingHost host, ServiceHost<BankProgram> bank, HttpClient bankClient, DateOnly date) : IAsyncDisposable
    {
        public StagingHost Host => host;
        public List<TopUp> TopUps { get; } = [];

        /// <summary>Every Kafka record the scenario produced.</summary>
        public List<DeliveryResult<string, byte[]>> Delivered { get; } = [];
        private DateTimeOffset BusinessTime => new(date.ToDateTime(new TimeOnly(10, 0), DateTimeKind.Utc));

        public async Task<RunOutcome> RunAsync()
        {
            await using var scope = host.Services.CreateAsyncScope();
            return await scope.ServiceProvider.GetRequiredService<ReconciliationRunner>().RunAsync(date, Ct);
        }

        /// <summary>A top-up at the bank: authorized, then captured, with the payment id as reference.</summary>
        public async Task<TopUp> CaptureAsync(long amountMinor)
        {
            var payment = Guid.NewGuid();
            using var authorize = new HttpRequestMessage(HttpMethod.Post, "/authorizations")
            {
                Content = JsonContent.Create(new { amountMinor, currency = "TRY", cardToken = "tok_ok", reference = payment.ToString() })
            };
            authorize.Headers.Add("Idempotency-Key", Guid.NewGuid().ToString("N"));
            using var authorized = await bankClient.SendAsync(authorize, Ct);
            authorized.StatusCode.ShouldBe(HttpStatusCode.Created);
            var authorizationId = (await authorized.Content.ReadFromJsonAsync<JsonElement>(Ct)).GetProperty("authorizationId").GetString();
            using var capture = new HttpRequestMessage(HttpMethod.Post, $"/authorizations/{authorizationId}/capture");
            capture.Headers.Add("Idempotency-Key", Guid.NewGuid().ToString("N"));
            using var captured = await bankClient.SendAsync(capture, Ct);
            captured.StatusCode.ShouldBe(HttpStatusCode.OK);
            var captureId = (await captured.Content.ReadFromJsonAsync<JsonElement>(Ct)).GetProperty("captureId").GetString()!;
            return new TopUp(payment, amountMinor, captureId);
        }

        /// <summary>The bank stamps captures with the current time; the business date is in the past.</summary>
        public async Task MoveCapturesToBusinessDateAsync()
        {
            await using var scope = bank.Services.CreateAsyncScope();
            await scope.ServiceProvider.GetRequiredService<BankDb>().Operations.Where(x => x.Kind == "Capture")
                .ExecuteUpdateAsync(update => update.SetProperty(x => x.OccurredAt, BusinessTime), Ct);
        }

        private DateTimeOffset InputTime => BusinessTime.AddMinutes(5);

        /// <summary>Each top-up's completion event, with its record timestamp on the business date.</summary>
        public async Task<List<DeliveryResult<string, byte[]>>> ProducePaymentsAsync()
        {
            var produced = new List<DeliveryResult<string, byte[]>>();
            foreach (var topUp in TopUps)
                produced.Add(await host.ProduceAsync(host.Options.PaymentEventsTopic, topUp.PaymentId, Wrap(new PaymentCompleted(
                    topUp.PaymentId, "TopUp", Guid.NewGuid(), topUp.AmountMinor, "TRY", null, Guid.NewGuid(), InputTime, topUp.CaptureId)), InputTime));
            Delivered.AddRange(produced);
            return produced;
        }

        /// <summary>Each top-up's two journal lines (clearing debit, wallet credit), with record timestamps on the business date.</summary>
        public async Task<List<DeliveryResult<string, byte[]>>> ProduceLedgerAsync()
        {
            var clearing = SystemAccounts.IdFor(SystemAccounts.BankClearing, "TRY");
            var produced = new List<DeliveryResult<string, byte[]>>();
            foreach (var topUp in TopUps)
            {
                var wallet = Guid.NewGuid();
                var entry = Guid.NewGuid();
                produced.Add(await host.ProduceAsync(host.Options.LedgerEntriesTopic, clearing, Wrap(new JournalEntryLinePosted(
                    entry, "TopUp", topUp.PaymentId, "TRY", InputTime, clearing, "Debit", topUp.AmountMinor, -topUp.AmountMinor, 1)), InputTime));
                produced.Add(await host.ProduceAsync(host.Options.LedgerEntriesTopic, wallet, Wrap(new JournalEntryLinePosted(
                    entry, "TopUp", topUp.PaymentId, "TRY", InputTime, wallet, "Credit", topUp.AmountMinor, topUp.AmountMinor, 2)), InputTime));
            }
            Delivered.AddRange(produced);
            return produced;
        }

        public async Task TamperAsync(object tampering)
        {
            using var response = await bankClient.PutAsJsonAsync("/settlement-tampering", tampering, Ct);
            response.StatusCode.ShouldBe(HttpStatusCode.NoContent);
        }

        public async ValueTask DisposeAsync()
        {
            await host.DisposeAsync();
            bankClient.Dispose();
            await bank.DisposeAsync();
        }
    }

    /// <summary>A lock that lets every caller through, but only once all of them have arrived.</summary>
    private sealed class BothPassLock(int callers) : IRunLock
    {
        private readonly TaskCompletionSource allArrived = new(TaskCreationOptions.RunContinuationsAsynchronously);
        private int arrived;

        public async Task<IAsyncDisposable?> TryAcquireAsync(DateOnly businessDate, CancellationToken ct)
        {
            if (Interlocked.Increment(ref arrived) == callers) allArrived.TrySetResult();
            await allArrived.Task.WaitAsync(TimeSpan.FromSeconds(30), ct);
            return new Released();
        }

        private sealed class Released : IAsyncDisposable
        {
            public ValueTask DisposeAsync() => ValueTask.CompletedTask;
        }
    }

